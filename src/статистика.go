package main

import (
	"encoding/json"
	"os"
	"strings"
	"sync"
)

// МодельNграмм хранит вероятности переходов между буквами
type МодельNграмм struct {
	Цепочки   map[string]map[string]int // "префикс" -> {"следующая_буква": частота}
	Всего     map[string]int            // "префикс" -> общее_количество_переходов
	РазмерN   int                       // Размер N-граммы (обычно 3 для триграмм)
	мю        sync.RWMutex
}

// НоваяМодель создаёт пустую модель
func НоваяМодель(размер int) *МодельNграмм {
	return &МодельNграмм{
		Цепочки: make(map[string]map[string]int),
		Всего:   make(map[string]int),
		РазмерN: размер,
	}
}

// ОбучитьНаСловах анализирует список слов и строит карту вероятностей
func (м *МодельNграмм) ОбучитьНаСловах(слова []string) {
	м.мю.Lock()
	defer м.мю.Unlock()
	for _, слово := range слова {
		м.обучитьНаСлове(слово)
	}
}

// ОбучитьНаСлове разбивает слово на N-граммы
func (м *МодельNграмм) ОбучитьНаСлове(слово string) {
	м.мю.Lock()
	defer м.мю.Unlock()
	м.обучитьНаСлове(слово)
}

func (м *МодельNграмм) обучитьНаСлове(слово string) {
	слово = "^" + strings.ToLower(слово) + "$" // Добавляем маркеры начала и конца
	руны := []rune(слово)
	
	for i := 0; i < len(руны)-1; i++ {
		// Берём префикс до РазмерN-1 символов
		начало := i - (м.РазмерN - 2)
		if начало < 0 {
			начало = 0
		}
		префикс := string(руны[начало : i+1])
		следующая := string(руны[i+1])

		if _, ок := м.Цепочки[префикс]; !ок {
			м.Цепочки[префикс] = make(map[string]int)
		}
		м.Цепочки[префикс][следующая]++
		м.Всего[префикс]++
	}
}

// Вероятность возвращает вероятность появления символа после данного префикса (0.0 - 1.0)
func (м *МодельNграмм) Вероятность(префикс string, символ string) float64 {
	м.мю.RLock()
	defer м.мю.RUnlock()
	
	// Если префикс слишком длинный, берем последние N-1 символов
	руныПрефикса := []rune(префикс)
	if len(руныПрефикса) >= м.РазмерN {
		префикс = string(руныПрефикса[len(руныПрефикса)-(м.РазмерN-1):])
	}

	// Пытаемся найти вероятность, если префикс не найден - пробуем более короткий (backoff)
	for len(префикс) >= 0 {
		if всего, ок := м.Всего[префикс]; ок {
			частота := м.Цепочки[префикс][символ]
			if частота > 0 {
				return float64(частота) / float64(всего)
			}
		}
		if len(префикс) == 0 {
			break
		}
		руны := []rune(префикс)
		префикс = string(руны[1:])
	}

	return 0.0001 // Минимальная вероятность для неизвестных переходов
}

// Сохранить записывает модель на диск
func (м *МодельNграмм) Сохранить(путь string) error {
	м.мю.RLock()
	defer м.мю.RUnlock()
	данные, err := json.Marshal(м)
	if err != nil {
		return err
	}
	return os.WriteFile(путь, данные, 0644)
}

// Загрузить читает модель с диска
func (м *МодельNграмм) Загрузить(путь string) error {
	м.мю.Lock()
	defer м.мю.Unlock()
	данные, err := os.ReadFile(путь)
	if err != nil {
		return err
	}
	return json.Unmarshal(данные, м)
}
