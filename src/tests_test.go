func TestТриеДобавитьИПоиск(t *testing.T) {
	трие := НовыйТрие()
	трие.ДобавитьСлово("привет")
	трие.ДобавитьСлово("приветик")
	трие.ДобавитьСлово("природа")
	трие.ДобавитьСлово("мир")

	результаты := трие.НайтиСловаСПрефиксом("при", 10)
	t.Logf("Префикс 'при': %v", результаты)
	if len(результаты) == 0 {
		t.Error("Ожидались слова для префикса 'при'")
	}

	найден := false
	for _, с := range результаты {
		if с == "привет" {
			найден = true
			break
		}
	}
	if !найден {
		t.Errorf("'привет' не найдено: %v", результаты)
	}

	результаты = трие.НайтиСловаСПрефиксом("привет", 10)
	t.Logf("Префикс 'привет': %v", результаты)
	найден = false
	for _, с := range результаты {
		if с == "привет" {
			найден = true
			break
		}
	}
	if !найден {
		t.Errorf("Точное слово 'привет' не найдено: %v", результаты)
	}
}

// Полный end-to-end тест с загрузкой словаря, раскладки и проверкой предсказаний
func TestПолныйЦиклПривет(t *testing.T) {
	МодельМаркова = НоваяМодель(3)
	КэшЧастотности = НовыиКэшЧастотностиСлов()

	Словари = НовыеСловариСлов()
	статус := Словари.ЗагрузитьСловари(
		"../data/dictionaries/russian_words.txt",
		"../data/dictionaries/english_words.txt",
	)
	if статус.Код != 0 {
		t.Fatalf("Ошибка загрузки словарей: %s", статус.Текст)
	}
	if !Словари.ЯвляетсяСловом("привет") {
		t.Error("'привет' нет в словарях!")
	}

	// Загружаем ТОЛЬКО активную раскладку
	Данные, _ := os.ReadFile("../data/layout.json")
	var rawMulti struct {
		ActiveLayout string            `json:"activeLayout"`
		Layouts      []РаскладкаДанные `json:"layouts"`
	}
	json.Unmarshal(Данные, &rawMulti)
	t.Logf("Active layout: '%s'", rawMulti.ActiveLayout)

	for _, д := range rawMulti.Layouts {
		if д.Name == rawMulti.ActiveLayout {
			раскладка := Раскладка{Данные: д}
			раскладка.Алфавит = make(map[ВиртуальныйКод]Кнопка)
			раскладка.Клавиатура = make([]ВиртуальныйКод, 0)
			раскладка.Ряды = ПарсингКлавиш(д.Keys)
			for _, ряд := range раскладка.Ряды {
				for _, к := range ряд {
					раскладка.Алфавит[к.VK] = Кнопка{
						код:        к.VK,
						строкаКода: к.Label,
						буквы:      map[string][]string{"en": к.En, "ру": к.Ru},
					}
					раскладка.Клавиатура = append(раскладка.Клавиатура, к.VK)
				}
			}
			ПрименитьРаскладку(&раскладка)
			break
		}
	}

	t.Logf("Алфавит: %d клавиш", len(Алфавит))
	t.Logf("Алгоритм: %d", АлгоритмПредсказания)

	// Строим VK коды для "привет"
	коды := []ВиртуальныйКод{}
	for _, б := range "привет" {
		буква := strings.ToLower(string(б))
		найдена := false
		for VK, к := range Алфавит {
			for _, кб := range к.буквы["ру"] {
				if strings.ToLower(кб) == буква {
					коды = append(коды, VK)
					найдена = true
					break
				}
			}
			if найдена {
				break
			}
		}
		if !найдена {
			t.Fatalf("Буква '%s' не найдена в Алфавит!", буква)
		}
	}
	t.Logf("VK коды для 'привет': %v", коды)

	// Проверка что VK коды совпадают с тем что нажимает пользователь (фыявйч)
	ожидаемыеКоды := []ВиртуальныйКод{65, 83, 90, 68, 81, 88}
	t.Logf("Ожидаемые (фыявйч):    %v", ожидаемыеКоды)
	if len(коды) == len(ожидаемыеКоды) {
		совпадают := true
		for i := range коды {
			if коды[i] != ожидаемыеКоды[i] {
				совпадают = false
				break
			}
		}
		t.Logf("Совпадают: %v", совпадают)
	} else {
		t.Logf("Длина не совпадает: %d vs %d", len(коды), len(ожидаемыеКоды))
	}

	индексыБукв := make([]int, len(коды))
	предсказания := ПредсказатьСлова(коды, индексыБукв)
	t.Logf("Всего предсказаний: %d", len(предсказания))

	найден := false
	for _, с := range предсказания {
		if с == "привет" {
			найден = true
			break
		}
	}
	if !найден {
		t.Errorf("'привет' НЕ найден! Все предсказания: %v", предсказания)
	} else {
		t.Log("OK: 'привет' найден в предсказаниях!")
	}
}

// Тест: что пользователь видит на экране и какие предсказания
func TestФйав_Дело(t *testing.T) {
	МодельМаркова = НоваяМодель(3)
	КэшЧастотности = НовыиКэшЧастотностиСлов()

	Словари = НовыеСловариСлов()
	Словари.ЗагрузитьСловари(
		"../data/dictionaries/russian_words.txt",
		"../data/dictionaries/english_words.txt",
	)

	// Загружаем только активную раскладку
	Данные, _ := os.ReadFile("../data/layout.json")
	var rawMulti struct {
		ActiveLayout string            `json:"activeLayout"`
		Layouts      []РаскладкаДанные `json:"layouts"`
	}
	json.Unmarshal(Данные, &rawMulti)
	for _, д := range rawMulti.Layouts {
		if д.Name == rawMulti.ActiveLayout {
			раскладка := Раскладка{Данные: д}
			раскладка.Алфавит = make(map[ВиртуальныйКод]Кнопка)
			раскладка.Ряды = ПарсингКлавиш(д.Keys)
			for _, ряд := range раскладка.Ряды {
				for _, к := range ряд {
					раскладка.Алфавит[к.VK] = Кнопка{
						код:        к.VK,
						строкаКода: к.Label,
						буквы:      map[string][]string{"en": к.En, "ру": к.Ru},
					}
				}
			}
			ПрименитьРаскладку(&раскладка)
			break
		}
	}

	// VK коды для "фйав" = 65 (A), 81 (Q), 70 (F), 68 (D)
	коды := []ВиртуальныйКод{65, 81, 70, 68}
	t.Logf("VK коды: %v", коды)
	t.Logf("Буквы по каждой клавише:")
	for _, код := range коды {
		if к, ок := Алфавит[код]; ок {
			t.Logf("  VK %d: ru=%v", код, к.буквы["ру"])
		}
	}

	// Трассировка шагов построения префиксов
	t.Logf("\n=== Трассировка построения префиксов ===")
	возможныеПрефиксы := []string{""}
	for шаг, код := range коды {
		новыеПрефиксы := []string{}
		кнопка, ок := Алфавит[код]
		if !ок {
			t.Fatalf("Код %d не найден в Алфавит", код)
		}
		всеБуквы := кнопка.буквы["ру"] // Только русские буквы для префиксов
		t.Logf("Шаг %d (VK %d): буквы %v, текущих префиксов: %d",
			шаг+1, код, всеБуквы, len(возможныеПрефиксы))

		for _, префикс := range возможныеПрефиксы {
			for _, буква := range всеБуквы {
				новыйПрефикс := префикс + strings.ToLower(буква)
				if Словари.ЯвляетсяПрефиксом(новыйПрефикс) {
					новыеПрефиксы = append(новыеПрефиксы, новыйПрефикс)
				}
			}
		}

		// Показываем новые префиксы (не больше 50)
		возможныеПрефиксы = новыеПрефиксы
		показ := возможныеПрефиксы
		if len(показ) > 50 {
			показ = показ[:50]
		}
		t.Logf("  → Префиксы (%d): %v", len(возможныеПрефиксы), показ)
	}

	t.Logf("\n=== Итоговые префиксы: %d ===", len(возможныеПрефиксы))
	естьДело := false
	for _, п := range возможныеПрефиксы {
		if п == "дело" {
			естьДело = true
			break
		}
	}
	t.Logf("Префикс 'дело' найден: %v", естьДело)
	if !естьДело {
		t.Errorf("'дело' не найдено среди %d префиксов! Все: %v", len(возможныеПрефиксы), возможныеПрефиксы)
	}

	// Полные предсказания
	индексы := make([]int, len(коды))
	предсказания := ПредсказатьСлова(коды, индексы)
	t.Logf("\n=== Предсказания (%d) ===", len(предсказания))
	for i, с := range предсказания {
		м := "  "
		if с == "дело" {
			м = "→"
		}
		t.Logf(" %s [%2d] %s", м, i+1, с)
	}

	найден := false
	for _, с := range предсказания {
		if с == "дело" {
			найден = true
			break
		}
	}
	if !найден {
		t.Errorf("'дело' НЕ найдено в предсказаниях!")
	} else {
		t.Log("OK: 'дело' найдено!")
	}
}

